export const LANGS = [
  { code: 'de', label: 'Deutsch', locale: 'de-CH' },
  { code: 'en', label: 'English', locale: 'en-GB' },
  { code: 'vi', label: 'Tiếng Việt', locale: 'vi-VN' },
];

let lang = 'de';
try { lang = localStorage.getItem('zaeme.lang') || (navigator.language || 'de').slice(0, 2); } catch { /* private mode */ }
if (!STR[lang]) lang = 'de';

export const getLang = () => lang;
export const locale = () => LANGS.find((l) => l.code === lang)?.locale ?? 'de-CH';
export function setLang(l) {
  if (!STR[l]) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem('zaeme.lang', l); } catch { /* ignore */ }
}
export function t(key, vars) {
  let s = STR[lang][key] ?? STR.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
